def profile_key(q1: float, qU: float) -> str:
    return f"{band(q1, FB)}|{band(qU, UB)}"


def score_set_prob(q1: float, qU: float, winner) -> tuple:
    """Kazandıran skorların kütlesi + küme metrikleri.
    winner(h, a) -> bool
    Döner: (olasılık, skor_sayısı, tek_skor_payı, kırılgan_mı)"""
    d = SCORE_DIST.get(profile_key(q1, qU))
    if not d:
        return 0.0, 0, 0.0, False
    win = {}
    for s, p in d.items():
        h, a = s.split("-")
        if winner(int(h), int(a)):
            win[s] = p
    tot = sum(win.values())
    if tot <= 0:
        return 0.0, 0, 0.0, False
    top = max(win.values()) / tot
    return tot, len(win), top, top > FRAGILE_TOP_SHARE


def combo_winner(res: str, second: str):
    """'0','1','2' × 'U','A','V','Y' → skor testi."""
    def f(h: int, a: int) -> bool:
        r = "1" if h > a else ("0" if h == a else "2")
        if r != res:
            return False
        t = h + a
        if second == "U":
            return t > 2.5
        if second == "A":
            return t < 2.5
        if second == "V":
            return h > 0 and a > 0
        return not (h > 0 and a > 0)
    return f


def ou_btts_winner(ou: str, kg: str):
    """'U'/'A' × 'V'/'Y' — SİMETRİ için (sonuçtan bağımsız)."""
    def f(h: int, a: int) -> bool:
        t = h + a
        ok1 = (t > 2.5) if ou == "U" else (t < 2.5)
        btts = h > 0 and a > 0
        ok2 = btts if kg == "V" else (not btts)
        return ok1 and ok2
    return f
